// El inglés vive en su propio módulo (src/lib/i18n-en.js) y NO entra en el
// bundle inicial: el español es el idioma por defecto y la mayoría de los
// visitantes nunca cambia a inglés. El hook useTranslation llama a esta
// función cuando el idioma activo es 'en'; hasta que resuelve, t() usa el
// diccionario en español (el fallback de siempre). La promesa se guarda
// para no pedir el módulo dos veces.
let englishPromise = null;
export function ensureEnglishTranslations() {
  if (TRANSLATIONS.en) return Promise.resolve(TRANSLATIONS.en);
  if (!englishPromise) {
    englishPromise = import('./i18n-en.js').then((m) => {
      TRANSLATIONS.en = m.EN_TRANSLATIONS;
      return TRANSLATIONS.en;
    }).catch((e) => {
      englishPromise = null;
      throw e;
    });
  }
  return englishPromise;
}

// Textos DINÁMICOS de estado de horario que genera src/lib/utils.js
// (getSmartScheduleInfo) y que pasan por t() sin clave de diccionario:
// "Cierra pronto (45m)", "Abre pronto (30m)", "Cerrado, abre hoy a las 9:00am"...
// El hook useTranslation los traduce con esta función cuando no hay clave
// en el diccionario ni fallback. Devuelve null si el texto no coincide con
// ningún patrón conocido (el hook usa entonces el fallback o el texto tal cual).
// Solo traduce a inglés; en español el texto ya viene en español.
const DIAS_ES_EN = {
  domingo: "Sunday",
  lunes: "Monday",
  martes: "Tuesday",
  "miércoles": "Wednesday",
  jueves: "Thursday",
  viernes: "Friday",
  "sábado": "Saturday",
};

export function translateDynamicStatus(text, lang) {
  if (lang !== "en" || typeof text !== "string") return null;
  let m;
  if ((m = text.match(/^cierra pronto \((\d+)m\)$/i))) return `Closing soon (${m[1]}m)`;
  if ((m = text.match(/^abre pronto \((\d+)m\)$/i))) return `Opening soon (${m[1]}m)`;
  if ((m = text.match(/^cerrado, abre hoy a las? (.+)$/i))) return `Closed, opens today at ${m[1]}`;
  if ((m = text.match(/^cerrado, abre mañana a las? (.+)$/i))) return `Closed, opens tomorrow at ${m[1]}`;
  if ((m = text.match(/^cerrado, abre el (domingo|lunes|martes|miércoles|jueves|viernes|sábado) a las? (.+)$/i))) {
    return `Closed, opens ${DIAS_ES_EN[m[1].toLowerCase()]} at ${m[2]}`;
  }
  return null;
}
